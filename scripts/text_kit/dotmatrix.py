ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def png(path, w, h, rows):
    raw = b''.join(b'\x00' + bytes(r) for r in rows)
    chunk = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def main():
    out = ROOT + '/cockpit/art/intercom/'
    glyphs = {c: g.split() for c, g in G.items()}
    assert all(len(r) == 5 for g in glyphs.values() for r in g) and all(len(g) == 7 for g in glyphs.values())
    with open(out + 'dotmatrix_5x7.json', 'w') as f:
        json.dump({'cell': [5, 7], 'advance': 6, 'note': "rows top to bottom, '1' = lit; map lower case to upper",
                   'glyphs': glyphs}, f, indent=1, ensure_ascii=False)
    # Preview sheet: 16 glyphs per row, 8 px cells scaled x4.
    chars = list(glyphs)
    cols, s = 16, 4
    nrow = (len(chars) + cols - 1) // cols
    w, h = cols * 8 * s, nrow * 10 * s
    img = [[24] * w for _ in range(h)]
    for k, c in enumerate(chars):
        ox, oy = (k % cols) * 8 + 1, (k // cols) * 10 + 1
        for y, row in enumerate(glyphs[c]):
            for x, b in enumerate(row):
                if b == '1':
                    for dy in range(s):
                        for dx in range(s):
                            img[(oy + y) * s + dy][(ox + x) * s + dx] = 235
    png(out + 'dotmatrix_5x7_sheet.png', w, h, img)
    print('DOTMATRIX glyphs=%d' % len(chars))


main()
